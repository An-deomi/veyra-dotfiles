#!/usr/bin/env python3
"""Manage Veyra user-defined Hyprland keybindings.

Built-in Veyra shortcuts remain in keybinds.lua. This helper stores custom
shortcuts separately and generates a Lua module loaded after the built-ins.
"""

import json
import os
import re
import sys
import tempfile
import uuid
from pathlib import Path

MODIFIERS = {"SUPER", "SHIFT", "CTRL", "ALT"}
ALLOWED_CATEGORIES = {
    "Applications",
    "Windows",
    "Workspaces",
    "System",
    "Quickshell",
    "My Shortcuts",
}
KEY_RE = re.compile(
    r"^(?:[A-Z0-9]|F(?:[1-9]|1[0-2])|"
    r"RETURN|ENTER|SPACE|TAB|ESC|ESCAPE|BACKSPACE|DELETE|INSERT|HOME|END|"
    r"PAGE_UP|PAGE_DOWN|UP|DOWN|LEFT|RIGHT|PRINT|PAUSE|MENU|"
    r"XF86[A-Z0-9_]+|mouse:\d+|code:\d+|[A-Z][A-Z0-9_]{0,31})$",
    re.IGNORECASE,
)


def paths():
    config_home = Path(os.environ.get("XDG_CONFIG_HOME") or (Path.home() / ".config"))
    state_home = Path(os.environ.get("XDG_STATE_HOME") or (Path.home() / ".local" / "state"))
    return (
        state_home / "veyra" / "keybinds_custom.json",
        config_home / "hypr" / "keybinds_custom.lua",
    )


def read_entries(json_path):
    try:
        data = json.loads(json_path.read_text(encoding="utf-8"))
        if not isinstance(data, list):
            return []
        return [entry for entry in data if isinstance(entry, dict)]
    except FileNotFoundError:
        return []
    except (OSError, json.JSONDecodeError):
        return []


def normalize_combo(value):
    if not isinstance(value, str) or not value.strip() or len(value) > 80:
        raise ValueError("Enter a shortcut such as SUPER + SHIFT + K.")
    parts = [part.strip() for part in value.split("+")]
    if any(not part for part in parts):
        raise ValueError("The shortcut contains an empty key or modifier.")
    mods = []
    for part in parts[:-1]:
        mod = part.upper()
        if mod in {"SUPER", "META", "WIN", "MOD"}:
            mod = "SUPER"
        elif mod in {"CONTROL", "CTRL"}:
            mod = "CTRL"
        if mod not in MODIFIERS:
            raise ValueError("Modifiers must be Super, Shift, Ctrl or Alt.")
        if mod in mods:
            raise ValueError("A modifier cannot be repeated.")
        mods.append(mod)
    key = parts[-1].strip()
    if key.upper() in MODIFIERS or not KEY_RE.fullmatch(key):
        raise ValueError("The final part must be a valid key (for example K, F8, Return or Print).")
    if len(key) == 1:
        key = key.upper()
    return " + ".join(mods + [key])


def lua_quote(value):
    return '"' + (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    ) + '"'


def atomic_write(path, content, mode=0o600):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temp_name, mode)
        os.replace(temp_name, path)
    finally:
        try:
            os.unlink(temp_name)
        except FileNotFoundError:
            pass


def _safe_comment(value):
    """Strip control characters so generated Lua comments stay single-line."""
    text = "".join(ch for ch in str(value) if ord(ch) >= 32 and ord(ch) != 127)
    return text or "(unnamed)"


def write_generated_lua(lua_path, entries):
    lines = [
        "-- Generated by Veyra Keybinds Manager.",
        "-- Edit shortcuts in Veyra Settings > Keybinds Manager, not this file.",
        "",
    ]
    last_category = None
    for entry in entries:
        category = entry.get("category", "My Shortcuts")
        if category != last_category:
            lines.append(f"-- {_safe_comment(category)}")
            last_category = category
        lines.append(f"-- {_safe_comment(entry['name'])}")
        lines.append(
            f"hl.bind({lua_quote(entry['combo'])}, "
            f"hl.dsp.exec_cmd({lua_quote(entry['command'])}))"
        )
    lines.append("")
    atomic_write(lua_path, "\n".join(lines))


def persist(json_path, lua_path, entries):
    atomic_write(json_path, json.dumps(entries, ensure_ascii=False, indent=2) + "\n")
    write_generated_lua(lua_path, entries)


def save(json_path, lua_path, payload):
    if not isinstance(payload, dict):
        raise ValueError("Invalid shortcut data.")
    name = str(payload.get("name", "")).strip()
    command = str(payload.get("command", "")).strip()
    category = str(payload.get("category", "My Shortcuts")).strip()
    combo = normalize_combo(payload.get("combo", ""))
    if not name or len(name) > 80:
        raise ValueError("Shortcut name must be between 1 and 80 characters.")
    if "\n" in name or "\r" in name:
        raise ValueError("Shortcut names must be a single line.")
    if not command or len(command) > 1000 or "\x00" in command:
        raise ValueError("Enter a command (up to 1000 characters).")
    if "\n" in command or "\r" in command:
        raise ValueError("Commands must be a single line.")
    if category not in ALLOWED_CATEGORIES:
        raise ValueError("Choose one of the available categories.")

    entries = read_entries(json_path)
    entry_id = str(payload.get("id", "")).strip() or uuid.uuid4().hex[:12]
    for entry in entries:
        if entry.get("id") != entry_id and str(entry.get("combo", "")).casefold() == combo.casefold():
            raise ValueError("That shortcut is already used by another custom shortcut.")

    updated = {
        "id": entry_id,
        "name": name,
        "category": category,
        "combo": combo,
        "command": command,
    }
    replaced = False
    for index, entry in enumerate(entries):
        if entry.get("id") == entry_id:
            entries[index] = updated
            replaced = True
            break
    if not replaced:
        entries.append(updated)
    persist(json_path, lua_path, entries)
    return updated


def delete(json_path, lua_path, entry_id):
    entries = read_entries(json_path)
    filtered = [entry for entry in entries if str(entry.get("id")) != entry_id]
    if len(filtered) == len(entries):
        raise ValueError("That custom shortcut no longer exists.")
    persist(json_path, lua_path, filtered)


def main():
    json_path, lua_path = paths()
    if len(sys.argv) < 2:
        raise ValueError("Expected save or delete action.")
    action = sys.argv[1]
    if action == "save":
        if len(sys.argv) < 3:
            raise ValueError("Missing shortcut details.")
        payload = json.loads(sys.argv[2])
        result = save(json_path, lua_path, payload)
        print(json.dumps({"ok": True, "entry": result}))
    elif action == "delete":
        if len(sys.argv) < 3:
            raise ValueError("Missing shortcut ID.")
        delete(json_path, lua_path, sys.argv[2])
        print(json.dumps({"ok": True}))
    else:
        raise ValueError("Unknown action.")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, json.JSONDecodeError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
