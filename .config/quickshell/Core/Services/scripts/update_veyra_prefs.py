#!/usr/bin/env python3
import json
import os
import re
import sys
import tempfile
from pathlib import Path

ALLOWED = {
    "cursor_theme",
    "cursor_size",
    "keyboard_layout",
    "shadow_glow_enabled",
    "shadow_glow_mode",
    "shadow_glow_opacity",
    "anim_curve",
    "anim_window_style",
    "anim_workspace_style",
    "anim_speed_factor",
    "anim_border_spin",
    "anim_border_speed",
    "anim_layers",
    "screen_shader",
}


def format_lua_value(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        formatted = f"{value:.2f}".rstrip("0").rstrip(".")
        return formatted if formatted else "0"
    if isinstance(value, str):
        escaped = value.replace("\\", "\\\\").replace('"', '\\"')
        return f'"{escaped}"'
    return str(value)

def main():
    try:
        updates = json.loads(sys.argv[1])

        if not isinstance(updates, dict) or not updates:
            raise ValueError("Expected a non-empty JSON object")
        if set(updates) - ALLOWED:
            raise ValueError("Unsupported Veyra preference")

        for key, value in updates.items():
            if key == "cursor_theme":
                if not isinstance(value, str) or not re.fullmatch(
                    r"[A-Za-z0-9 _.-]{1,100}", value
                ):
                    raise ValueError("Invalid cursor theme name")
            elif key == "cursor_size":
                if isinstance(value, bool) or not isinstance(value, int) or not 1 <= value <= 256:
                    raise ValueError("Cursor size must be an integer from 1 to 256")
            elif key == "keyboard_layout":
                # Comma separated xkb layout codes, e.g. "us,ara".
                if not isinstance(value, str) or not re.fullmatch(
                    r"[A-Za-z0-9_-]{1,20}(,[A-Za-z0-9_-]{1,20}){0,7}", value
                ):
                    raise ValueError("Invalid keyboard layout list")
            elif key == "shadow_glow_enabled":
                if not isinstance(value, bool):
                    raise ValueError("shadow_glow_enabled must be a boolean")
            elif key == "shadow_glow_mode":
                if value not in ("accent", "complementary"):
                    raise ValueError("shadow_glow_mode must be 'accent' or 'complementary'")
            elif key == "shadow_glow_opacity":
                if isinstance(value, bool) or not isinstance(value, int) or not 5 <= value <= 100:
                    raise ValueError("shadow_glow_opacity must be an integer from 5 to 100")
            elif key == "anim_curve":
                if value not in ("overshot", "spring", "ease", "snappy"):
                    raise ValueError("anim_curve must be overshot, spring, ease, or snappy")
            elif key == "anim_window_style":
                if value not in ("popin 80%", "popin 60%", "slide", "gnomed"):
                    raise ValueError("Invalid anim_window_style")
            elif key == "anim_workspace_style":
                if value not in ("slide", "slidevert", "slidefade 20%", "fade"):
                    raise ValueError("Invalid anim_workspace_style")
            elif key == "anim_speed_factor":
                if isinstance(value, bool) or not isinstance(value, (int, float)) or not 0.2 <= float(value) <= 3.0:
                    raise ValueError("anim_speed_factor must be between 0.2 and 3.0")
            elif key == "anim_border_spin":
                if not isinstance(value, bool):
                    raise ValueError("anim_border_spin must be a boolean")
            elif key == "anim_border_speed":
                if isinstance(value, bool) or not isinstance(value, int) or not 10 <= value <= 120:
                    raise ValueError("anim_border_speed must be an integer from 10 to 120")
            elif key == "anim_layers":
                if not isinstance(value, bool):
                    raise ValueError("anim_layers must be a boolean")
            elif key == "screen_shader":
                if value not in ("none", "vibrance", "film-grain", "crt", "warm"):
                    raise ValueError("Invalid screen_shader")

        config_home = Path(
            os.environ.get("XDG_CONFIG_HOME", str(Path.home() / ".config"))
        )
        target = config_home / "hypr" / "veyra-settings.lua"
        target.parent.mkdir(parents=True, exist_ok=True)

        if target.exists():
            lines = target.read_text(encoding="utf-8").splitlines()
        else:
            lines = [
                "-- Generated by Veyra Settings. Do not edit by hand.",
                "return {",
                "}",
            ]

        found = set()
        output = []

        allowed_pattern = "|".join(sorted(ALLOWED))
        line_re = re.compile(rf"^([ \t]*)({allowed_pattern})[ \t]*=")

        for line in lines:
            match = line_re.match(line)

            if match and match.group(2) in updates:
                key = match.group(2)
                lua_value = format_lua_value(updates[key])

                output.append(f"{match.group(1)}{key} = {lua_value},")
                found.add(key)
            else:
                output.append(line)

        missing = set(updates) - found
        if missing:
            closing = next(
                (i for i in range(len(output) - 1, -1, -1)
                 if output[i].strip() == "}"),
                None,
            )
            if closing is None:
                raise ValueError("Could not find closing Lua table brace")

            additions = [
                f"    {key} = {format_lua_value(updates[key])},"
                for key in sorted(missing)
            ]

            output[closing:closing] = additions

        content = "\n".join(output) + "\n"

        fd, temp_name = tempfile.mkstemp(
            prefix=".veyra-settings.", dir=target.parent, text=True
        )
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as handle:
                handle.write(content)
                handle.flush()
                os.fsync(handle.fileno())

            os.chmod(temp_name, 0o600)
            os.replace(temp_name, target)
        finally:
            if os.path.exists(temp_name):
                os.unlink(temp_name)

        print(f"Updated {target}")

    except Exception as exc:
        print(f"Veyra preferences update failed: {exc}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
