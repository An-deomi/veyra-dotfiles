#!/usr/bin/env python3
"""Manage Veyra-owned monitor profiles and custom Hyprland window rules."""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any


def config_home() -> Path:
    return Path(os.environ.get("XDG_CONFIG_HOME", str(Path.home() / ".config")))


def state_home() -> Path:
    return Path(os.environ.get("XDG_STATE_HOME", str(Path.home() / ".local/state")))


def atomic_write(path: Path, content: str, mode: int = 0o600) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent, text=True)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temp_name, mode)
        os.replace(temp_name, path)
    finally:
        try:
            os.unlink(temp_name)
        except FileNotFoundError:
            pass


def lua_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    escaped = escaped.replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    return f'"{escaped}"'


def lua_bool(value: bool) -> str:
    return "true" if value else "false"


def read_stdin_json() -> Any:
    raw = sys.stdin.read()
    try:
        return json.loads(raw or "null")
    except json.JSONDecodeError as exc:
        raise ValueError(f"Invalid JSON input: {exc}") from exc


def rule_paths() -> tuple[Path, Path]:
    state = state_home() / "veyra" / "window_rules.json"
    lua = config_home() / "hypr" / "windowrules.local.lua"
    return state, lua


def normalize_monitors(raw: Any) -> list[dict[str, Any]]:
    if not isinstance(raw, list) or not raw:
        raise ValueError("Select at least one connected monitor")
    if len(raw) > 8:
        raise ValueError("A maximum of 8 connected monitors is supported")

    result: list[dict[str, Any]] = []
    seen: set[str] = set()
    for item in raw:
        if not isinstance(item, dict):
            raise ValueError("Each monitor entry must be an object")
        output = str(item.get("output", "")).strip()
        mode = str(item.get("mode", "preferred")).strip()
        position = str(item.get("position", "auto")).strip()
        try:
            scale = float(item.get("scale", 1.0))
            transform = int(item.get("transform", 0))
            vrr = int(item.get("vrr", 0))
        except (TypeError, ValueError) as exc:
            raise ValueError(f"Invalid display settings for {output or 'monitor'}") from exc

        if not re.fullmatch(r"[A-Za-z0-9_.:-]{1,80}", output):
            raise ValueError("Invalid monitor output name")
        if output in seen:
            raise ValueError(f"Duplicate monitor output: {output}")
        seen.add(output)
        if mode != "preferred" and not re.fullmatch(r"\d{3,5}x\d{3,5}@[0-9.]+Hz?", mode):
            raise ValueError(f"Unsupported mode format for {output}: {mode}")
        if not re.fullmatch(r"auto|-?\d{1,5}x-?\d{1,5}", position):
            raise ValueError(f"Invalid position for {output}")
        if not (0.5 <= scale <= 3.0):
            raise ValueError(f"Scale for {output} must be between 0.5 and 3.0")
        if transform not in range(8):
            raise ValueError(f"Transform for {output} must be between 0 and 7")
        if vrr not in (-1, 0, 1, 2, 3):
            raise ValueError(f"VRR mode for {output} must be -1, 0, 1, 2 or 3")
        result.append({
            "output": output,
            "mode": mode,
            "position": position,
            "scale": round(scale, 3),
            "transform": transform,
            "vrr": vrr,
        })
    return result


def write_monitor_configuration(monitors: list[dict[str, Any]]) -> dict[str, Any]:
    lua_path = config_home() / "hypr" / "monitors.lua"
    lua_lines = [
        "-- Generated by Veyra Display Settings.",
        "-- Edit this file through Veyra Settings.",
        "",
    ]

    for monitor in monitors:
        lua_lines.extend([
            "hl.monitor({",
            f'    output = {lua_string(monitor["output"])},',
            f'    mode = {lua_string(monitor["mode"])},',
            f'    position = {lua_string(monitor["position"])},',
            f'    scale = {monitor["scale"]:g},',
            f'    transform = {monitor["transform"]},',
            f'    vrr = {monitor["vrr"]},',
            "})",
            "",
        ])

    atomic_write(lua_path, "\n".join(lua_lines).rstrip() + "\n")

    return {
        "ok": True,
        "message": f"Saved {len(monitors)} monitor setting(s) to monitors.lua.",
        "path": str(lua_path),
    }


def save_monitors(apply: bool) -> dict[str, Any]:
    monitors = normalize_monitors(read_stdin_json())
    result = write_monitor_configuration(monitors)

    if apply:
        try:
            completed = subprocess.run(
                ["hyprctl", "reload"],
                check=False,
                capture_output=True,
                text=True,
                timeout=15,
            )
        except (FileNotFoundError, subprocess.TimeoutExpired) as exc:
            raise RuntimeError(
                f"Monitor file was saved, but Hyprland reload failed: {exc}"
            ) from exc

        if completed.returncode != 0:
            detail = (
                completed.stderr or completed.stdout or "hyprctl reload failed"
            ).strip()
            raise RuntimeError(
                f"Monitor file was saved, but Hyprland reload failed: {detail}"
            )

        result["message"] = (
            f"Saved {len(monitors)} monitor setting(s) and reloaded Hyprland."
        )
    else:
        result["message"] = (
            f"Saved {len(monitors)} monitor setting(s) to monitors.lua."
        )

    return result


def normalize_rules(raw: Any) -> list[dict[str, Any]]:
    if not isinstance(raw, list):
        raise ValueError("Window rules must be a list")
    if len(raw) > 100:
        raise ValueError("A maximum of 100 custom window rules is supported")

    result: list[dict[str, Any]] = []
    seen_matchers: set[tuple[str, str]] = set()
    for item in raw:
        if not isinstance(item, dict):
            raise ValueError("Each rule must be an object")
        class_name = str(item.get("class", "")).strip()
        title = str(item.get("title", "")).strip()
        workspace = str(item.get("workspace", "")).strip()
        monitor = str(item.get("monitor", "")).strip()
        if not class_name and not title:
            raise ValueError("A rule needs an application class or window title")
        if len(class_name) > 160 or len(title) > 160:
            raise ValueError("Match patterns must be 160 characters or fewer")
        matcher = (class_name.casefold(), title.casefold())
        if matcher in seen_matchers:
            raise ValueError("A window rule with the same application/title match already exists. Edit the existing rule instead.")
        seen_matchers.add(matcher)
        for label, pattern in (("Application class", class_name), ("Window title", title)):
            if pattern:
                try:
                    re.compile(pattern)
                except re.error as exc:
                    raise ValueError(f"{label} is not a valid regular expression: {exc}") from exc
        if len(workspace) > 64 or (workspace and not re.fullmatch(r"[A-Za-z0-9:_-]+", workspace)):
            raise ValueError("Workspace may contain letters, numbers, :, _ and - only")
        if monitor and not re.fullmatch(r"[A-Za-z0-9_.:-]{1,80}", monitor):
            raise ValueError("Monitor name contains unsupported characters")
        try:
            opacity = float(item.get("opacity", 1.0))
            rounding = int(item.get("rounding", 0))
        except (TypeError, ValueError) as exc:
            raise ValueError("Opacity and rounding must be numbers") from exc
        if not (0.5 <= opacity <= 1.0):
            raise ValueError("Opacity must be between 50% and 100%")
        if not (0 <= rounding <= 40):
            raise ValueError("Rounding must be between 0 and 40 pixels")
        float_window = bool(item.get("float", False))
        center = bool(item.get("center", False))
        pin = bool(item.get("pin", False))
        if center or pin:
            float_window = True
        result.append({
            "class": class_name,
            "title": title,
            "float": float_window,
            "center": center,
            "pin": pin,
            "maximize": bool(item.get("maximize", False)),
            "no_blur": bool(item.get("no_blur", False)),
            "no_shadow": bool(item.get("no_shadow", False)),
            "no_anim": bool(item.get("no_anim", False)),
            "no_focus": bool(item.get("no_focus", False)),
            "opacity": round(opacity, 2),
            "rounding": rounding,
            "workspace": workspace,
            "monitor": monitor,
        })
    return result


def save_rules() -> dict[str, Any]:
    rules = normalize_rules(read_stdin_json())
    state_path, lua_path = rule_paths()
    lua_lines = ["-- Generated by Veyra Window Rules Manager. Edit in Veyra Settings.", "local rules = {"]
    for rule in rules:
        match_parts = []
        if rule["class"]:
            match_parts.append(f'class = {lua_string(rule["class"])}')
        if rule["title"]:
            match_parts.append(f'title = {lua_string(rule["title"])}')
        action_parts = [f'match = {{ {", ".join(match_parts)} }}']
        if rule["float"]:
            action_parts.append("float = true")
        if rule["center"]:
            action_parts.append("center = true")
        if rule["pin"]:
            action_parts.append("pin = true")
        if rule["maximize"]:
            action_parts.append("maximize = true")
        if rule["no_blur"]:
            action_parts.append("no_blur = true")
        if rule["no_shadow"]:
            action_parts.append("no_shadow = true")
        if rule["no_anim"]:
            action_parts.append("no_anim = true")
        if rule["no_focus"]:
            action_parts.append("no_focus = true")
        if rule["rounding"]:
            action_parts.append(f'rounding = {rule["rounding"]}')
        if rule["opacity"] < 1.0:
            opacity_value = f'{rule["opacity"]:.2f} override'
            action_parts.append(f'opacity = {lua_string(opacity_value)}')
        if rule["workspace"]:
            action_parts.append(f'workspace = {lua_string(rule["workspace"])}')
        if rule["monitor"]:
            action_parts.append(f'monitor = {lua_string(rule["monitor"])}')
        lua_lines.append("    { " + ", ".join(action_parts) + " },")
    lua_lines.extend(["}", "for _, rule in ipairs(rules) do", "    hl.window_rule(rule)", "end"])
    atomic_write(state_path, json.dumps(rules, indent=2) + "\n")
    atomic_write(lua_path, "\n".join(lua_lines) + "\n")
    return {"ok": True, "message": f"Saved {len(rules)} custom window rule(s).", "path": str(lua_path)}


def read_json(path: Path) -> Any:
    try:
        with path.open("r", encoding="utf-8") as handle:
            return json.load(handle)
    except FileNotFoundError:
        return []


def main() -> int:
    if len(sys.argv) < 2:
        print(json.dumps({"ok": False, "message": "Missing command"}))
        return 2
    command = sys.argv[1]
    try:
        if command == "list-rules":
            state_path, _ = rule_paths()
            print(json.dumps(read_json(state_path)))
            return 0
        if command == "save-rules":
            print(json.dumps(save_rules()))
            return 0
        if command == "save-monitors":
            apply = "--no-apply" not in sys.argv[2:]
            print(json.dumps(save_monitors(apply)))
            return 0
        raise ValueError(f"Unknown command: {command}")
    except (ValueError, RuntimeError, OSError) as exc:
        print(json.dumps({"ok": False, "message": str(exc)}))
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
